/**
 * API types, mirrored by hand from the backend's structs. Keep in sync.
 *
 * Timestamps are RFC 3339 strings. Ids are opaque strings (UUIDs).
 */

/**
 * `GET /v1/me`: the signed-in user as the backend knows them. The backend
 * doesn't implement it yet; fields beyond `id` are optional until it does,
 * and the UI falls back to Clerk's profile for anything missing.
 * @typedef {object} Me
 * @property {string} id
 * @property {string} [email] The verified email the server knows (invites go to it).
 * @property {string} [name]
 * @property {string | null} [avatar_url]
 */

/**
 * `GET /v1/workspaces`: the workspaces the user belongs to.
 * @typedef {object} Workspace
 * @property {string} id
 * @property {string} name
 * @property {string | null} icon Emoji, or null.
 * @property {string} created_at
 */

/**
 * A page. `title` is the single source of a page's name (the editor's first
 * line doesn't duplicate it).
 *
 * `position` orders siblings: a fractional index key (`lib/fractional-index.js`),
 * compared by code unit, never by locale collation.
 *
 * `cover` is an opaque string the client interprets: `color:<name>` or
 * `gradient:<name>` for the presets in `routes/page/covers.js`, or
 * `file:<id>` for an uploaded image (`api/files.js`). `icon` is an emoji or
 * `file:<id>`.
 *
 * Archived pages are in the trash. Archiving a page archives its whole
 * subtree; `archived_at` is set on every page in it.
 *
 * `role` is the signed-in user's role on the page (`api/roles.js`): with
 * `comment` or `view` the page is read-only for them.
 *
 * @typedef {object} Page
 * @property {string} id
 * @property {string} workspace_id
 * @property {string | null} parent_id Null at the top level.
 * @property {string} title Empty string for "Untitled".
 * @property {string | null} icon
 * @property {string | null} cover
 * @property {string} position
 * @property {boolean} has_children Has at least one non-archived child.
 * @property {string | null} archived_at
 * @property {string} created_at
 * @property {string} updated_at
 * @property {import("./roles.js").Role} [role] Missing from servers before roles: editable.
 * @property {PageKind} [kind] Missing from servers before databases: "page".
 * @property {Record<string, PropertyValue>} [properties] A row's values (rows only).
 */

/**
 * What a page is (docs/databases.md): an ordinary page, a database, or one
 * of a database's rows (its child pages, which the sidebar doesn't list).
 * @typedef {"page" | "database" | "row"} PageKind
 */

/**
 * One page in the sidebar tree: just enough to draw a row.
 * `GET /v1/workspaces/:id/tree?parent_id=` returns one level of these,
 * sorted by `position`.
 * @typedef {object} TreeNode
 * @property {string} id
 * @property {string | null} parent_id
 * @property {string} title
 * @property {string | null} icon
 * @property {string} position
 * @property {boolean} has_children Draws the expand chevron before the children are loaded.
 * @property {PageKind} [kind]
 */

/**
 * One result of `GET /v1/workspaces/:id/pages?query=` (a page title search,
 * for `@` mentions): a live page and its ancestors' titles, outermost first.
 * @typedef {object} PageMatch
 * @property {string} id
 * @property {string | null} parent_id
 * @property {string} title
 * @property {string | null} icon
 * @property {string[]} path
 */

/**
 * `POST /v1/pages`. `id` is generated by the client so optimistic UI never
 * has to swap a temporary id; the server must accept it (and treat a repeat
 * as the same create). `after_id` null puts the page first among its
 * siblings; omitted, last.
 * @typedef {object} CreatePageInput
 * @property {string} id
 * @property {string} workspace_id
 * @property {string | null} parent_id
 * @property {string | null} [after_id]
 * @property {string} [title]
 * @property {string | null} [icon]
 * @property {string | null} [cover]
 * @property {"page" | "database"} [kind] A database gets a title property and a "Table" view.
 */

/**
 * `PATCH /v1/pages/:id`. Only the fields present change.
 * @typedef {object} UpdatePageInput
 * @property {string} [title]
 * @property {string | null} [icon]
 * @property {string | null} [cover]
 * @property {Record<string, PropertyValue | null>} [properties] A row's values to change (merged; null clears one).
 */

/**
 * `POST /v1/pages/:id/move`. `after_id` null: first among the new siblings.
 * @typedef {object} MovePageInput
 * @property {string | null} parent_id
 * @property {string | null} after_id
 */

// Databases (docs/databases.md)

/**
 * @typedef {"title" | "text" | "number" | "select" | "multi_select" | "status" | "date" | "person" | "checkbox" | "url"} PropertyType
 */

/**
 * A select, multi-select or status option. `group` is a status option's.
 * @typedef {object} SelectOption
 * @property {string} id
 * @property {string} name
 * @property {string} color One of `databases/schema.js`'s OPTION_COLORS.
 * @property {"to_do" | "in_progress" | "complete"} [group]
 */

/**
 * One of a database's properties (a column). `options` only on the option types.
 * @typedef {object} Property
 * @property {string} id
 * @property {string} name
 * @property {PropertyType} type
 * @property {SelectOption[]} [options]
 */

/**
 * A stored value: text, URL, date ("YYYY-MM-DD") and option ids are
 * strings; multi-select and person are lists of ids; numbers; checkboxes
 * (only `true` is stored).
 * @typedef {string | number | boolean | string[]} PropertyValue
 */

/**
 * @typedef {object} FilterCondition
 * @property {string} property_id
 * @property {string} operator
 * @property {string | number | boolean} [value]
 */

/** @typedef {{ and: Filter[] } | { or: Filter[] }} FilterGroup */
/** @typedef {FilterGroup | FilterCondition} Filter */

/**
 * @typedef {object} Sort
 * @property {string} property_id
 * @property {"ascending" | "descending"} direction
 */

/**
 * A view's setting for one column. Properties not listed come after, visible.
 * @typedef {object} Column
 * @property {string} property_id
 * @property {number} [width] px
 * @property {boolean} [hidden]
 */

/** @typedef {"table" | "board"} ViewType */

/**
 * A view. Every view has the board's settings (docs/databases.md, Section
 * 3.1); a table ignores them, so changing `type` keeps both layouts'.
 * @typedef {object} View
 * @property {string} id
 * @property {string} name
 * @property {ViewType} type
 * @property {string} position
 * @property {FilterGroup | null} filter
 * @property {Sort[]} sorts
 * @property {Column[]} columns A table's.
 * @property {string | null} group_by A board's columns: a select or status property.
 * @property {string[]} card_properties Shown on a board's cards, under the title.
 * @property {string[]} hidden_groups A board's hidden columns: option ids, "" for rows without a value.
 * @property {number | null} page_size Rows a table shows per page; null: the default (50).
 */

/**
 * A query narrowed to one board column: rows whose value of a select or
 * status property is `value`, or empty when it's null.
 * @typedef {object} RowGroup
 * @property {string} property_id
 * @property {string | null} value
 */

/**
 * `GET /v1/databases/:id`: a database's schema and views. The database's
 * title, icon and place are its page's.
 * @typedef {object} Database
 * @property {string} id
 * @property {string} workspace_id
 * @property {Property[]} properties The title property first.
 * @property {View[]} views In tab order.
 */

/**
 * One row, as a query returns it.
 * @typedef {object} Row
 * @property {string} id The row's page id.
 * @property {string} database_id
 * @property {string} title
 * @property {string | null} icon
 * @property {Record<string, PropertyValue>} properties
 * @property {string} position
 * @property {string} created_at
 * @property {string} updated_at
 */

/**
 * `POST /v1/databases/:id/query`: one page of the matching rows.
 * @typedef {object} RowPage
 * @property {Row[]} rows
 * @property {number} total Every matching row.
 */

/**
 * `GET /v1/workspaces/:id/members`. Name and picture are what the member's
 * own client set (`PATCH /v1/me`); null until then.
 * @typedef {object} Member
 * @property {string} id
 * @property {import("./roles.js").Role} role
 * @property {string | null} name
 * @property {string | null} avatar_url
 */

